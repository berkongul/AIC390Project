def price(rng, low, high):
    """A shop-like price such as 2,899 TL."""
    value = rng.randrange(low, high, 100) + 99
    return f"{value:,} TL"


def colours(rng, n=None):
    picked = rng.sample(COLOURS, n or rng.choice((2, 3)))
    return ", ".join(picked[:-1]) + " and " + picked[-1]


