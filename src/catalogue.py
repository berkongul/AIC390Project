"""Week 4 generated product catalogue: scales the corpus to about 10,000 chunks.

Owner: Orhun Cerit (data and retrieval lead).

Week 3 feedback asked for a much larger corpus. A real shop has hundreds of products whose
pages look almost the same, and whose codes differ by one digit (TR-220, TR-221, TR-202).
That is the hard case for retrieval: embeddings place near-identical codes close together,
keyword search (BM25) keeps them apart. This module generates such a catalogue.

  * About 2,500 synthetic products in 11 families, 4 sections each (about 10,000 chunks).
  * Deterministic: the same SEED always gives the same catalogue, so every number that
    uses it can be reproduced from the repository (rule R8). Nothing is written to disk.
  * Consistent with the store policies in data/docs: footwear warranty 12 months, outerwear
    and bags 24 months, running and trail shoes fit half a size small, hiking boots and
    sneakers fit true to size.
  * The codes of the 11 hand-written product pages are never reused, but their neighbours
    are always generated (TR-219, TR-221, TR-202, ...) to make retrieval hard on purpose.
  * Synthetic and fictional (rule R10).

The documents are loaded together with data/docs by src/corpus.py (load_documents()).

Run:  python src/catalogue.py            summary of the catalogue
      python src/catalogue.py TR-247     print one product page
"""
