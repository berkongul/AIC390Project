def neighbours(code):
    """Codes one digit away from an existing code: TR-220 -> TR-219, TR-221, TR-210, TR-230, TR-202."""
    prefix, number = code.split("-")
    if not number.isdigit() or len(number) != 3:
        return set()
    n = int(number)
    out = {n - 1, n + 1, n - 10, n + 10}
    swapped = number[0] + number[2] + number[1]
    out.add(int(swapped))
    return {f"{prefix}-{x:03d}" for x in out if 100 <= x <= 999}


def generate(seed=SEED):
    """Return the catalogue as a list of (doc_id, meta, body) tuples, always in the same order."""
    rng = random.Random(seed)
    names = [f"{a} {b}" for a in FIRST for b in SECOND if a != b]
    rng.shuffle(names)
    forced = set().union(*(neighbours(c) for c in EXISTING)) - EXISTING
    products = []
    for prefix, kind, count, _ in FAMILIES:
        must = sorted(c for c in forced if c.startswith(prefix + "-"))
        pool = [f"{prefix}-{n:03d}" for n in range(100, 1000)]
        pool = [c for c in pool if c not in EXISTING and c not in must]
        codes = must + rng.sample(pool, count - len(must))
        products += [(prefix, kind, code) for code in sorted(codes)]
    sections_by_prefix = {p: f for p, _, _, f in FAMILIES}
    docs = []
    for i, (prefix, kind, code) in enumerate(products):
        name = names[i]
        title = f"{code} {name} {kind}"
        meta = {"id": f"product-{code.lower()}", "title": title, "type": "product",
                "access": "public", "version": "1.0", "updated": UPDATED,
                "store": "Lodos Outfitters (fictional)", "source": SOURCE}
        sections = sections_by_prefix[prefix](rng, code, name)
        body = f"# {title}\n" + "".join(f"\n## {head}\n{text}\n" for head, text in sections.items())
        docs.append((meta["id"], meta, body))
    return docs


def main():
    docs = generate()
    if len(sys.argv) > 1:
        wanted = "product-" + sys.argv[1].lower()
        for doc_id, meta, body in docs:
            if doc_id == wanted:
                print(body)
                return
        raise SystemExit(f"{sys.argv[1]} is not in the generated catalogue")
    families = Counter(doc_id.split("-")[1].upper() for doc_id, _, _ in docs)
    sections = sum(body.count("\n## ") for _, _, body in docs)
    print(f"{len(docs)} generated products, {sections} sections (chunks), seed {SEED}")
    print(", ".join(f"{k} {v}" for k, v in families.items()))


if __name__ == "__main__":
    main()
